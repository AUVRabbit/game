#==============================================================================
# ■ FmodSoundSystem
#------------------------------------------------------------------------------
# 　    RGSS新聲音系統模塊，用於解決自Windows Vista之後微軟移除了DirectSound的
#   硬件加速導致的一系列聲音播放速度變慢的問題。
#
#   作者：宇文隳
#
#   本系統基於個人免費的音樂引擎 FMod Ex v4.06.16
#   FMod官網：http://www.fmod.org/
#
#
#   注意：請勿修改本模塊的任何定義。
#
#
#   系統版本：v0.3
#
#   特色：
#         1、脫離DirectSound，而使用跨平臺的FMod音頻引擎，解決在Vista和Win7
#            上RMXP的5秒啟動的問題。
#         2、支持多種格式的音樂，包括：
#            AIFF/ASF/ASX/DLS/FLAC/FSB/IT/M3U/MID/MOD/MP2/MP3/OGG/PLS/RAW/S3M/
#            VAG/WAV/WAX/WMA/XM/XMA/XWMA/AudioQueue。
#         3、支持最多36個聲道的音樂同時播放（默認關閉，為單聲道，慎用）。
#         4、RMXP/VX通用，也可以解決RMVX在戰鬥時音樂播放假死的問題。
#         5、低系統佔用聲音播放。
#
#   注意：
#         1、使用前最好設置好RTP的位置。
#         2、音樂搜索的播放順序是先在本遊戲目錄下搜索音樂文件，如果找不到才在
#            RTP中搜索。
#         3、沒有播放文件的時候並不會報錯，只是沒有聲音。
#         4、如果沒有特殊需要，儘量不要使用多聲道。
#         5、音樂淡出的處理在使用了Ruby內部的線程，請不要殺死該線程。
#         6、不要在同一文件夾下放入文件名相同但擴展名不同的兩個音樂文件，比如
#            "a.mp3"和"a.ogg"。
#
#   更新日誌：
#   2011.08.13
#     FmodSoundSystem v0.1版發佈，提供對默認的Audio音樂引擎的完全覆蓋。
#     當前版本只能在32位系統上使用。
#     音樂淡出基本實現，但不能實現高精度淡出。
#
#   2011.08.15
#     增加了只在WinXP以上版本Windows中引擎開啟的判定。
#
#   2011.08.17
#     修正了操作系統版本判定的錯誤
#
#   2011.11.15
#     修正了ME和SE循環播放的問題##   2011.11.16
#     重定義了RPG::Animation解決戰鬥SE無法播放的問題，以及使用内部线程解决了ME
#   和BGM同时播放的问题。
#
#
#==============================================================================
module FmodSoundSystem
  
  #--------------------------------------------------------------------------
  # ● 常量定義
  #--------------------------------------------------------------------------
  
  VERSION = 0.3
  ONE_SOUND_TRACK = 0
  OVER_SOUND_TRACK = 1
  NO_FORCE_CHANGE = 0
  FORCE_CHANGE = 1
  
  #--------------------------------------------------------------------------
  # ● 設置是否使用單聲道（最多36個聲道）
  #--------------------------------------------------------------------------
  SOUND_TRACK = ONE_SOUND_TRACK

  #--------------------------------------------------------------------------
  # ● 設置DLL位置
  #--------------------------------------------------------------------------  
  DLL = ""
  
  #--------------------------------------------------------------------------
  # ● 設置是否覆蓋原有Audio模塊
  #--------------------------------------------------------------------------    
  REWRITE = true
  
  #--------------------------------------------------------------------------
  # ● 設置RTP位置
  #--------------------------------------------------------------------------
  RTP = "D:/RPG Maker系列/RPG Maker XP/RGSS/Standard"
  
  #--------------------------------------------------------------------------
  # ● API聲明
  #--------------------------------------------------------------------------
  
  INITIALIZE_SYSTEM = Win32API.new(DLL + "FmodMS.dll", "initialize_system",\
                                   "i", "i")
  BGM_PLAY = Win32API.new(DLL + "FmodMS.dll", "bgm_play", "pii", "i")
  BGS_PLAY = Win32API.new(DLL + "FmodMS.dll", "bgs_play", "pii", "i")
  SE_PLAY = Win32API.new(DLL + "FmodMS.dll", "se_play", "pii", "i")
  ME_PLAY = Win32API.new(DLL + "FmodMS.dll", "me_play", "pii", "i")
  BGM_STOP = Win32API.new(DLL + "FmodMS.dll", "bgm_stop", "v", "i")
  BGS_STOP = Win32API.new(DLL + "FmodMS.dll", "bgs_stop", "v", "i")
  SE_STOP = Win32API.new(DLL + "FmodMS.dll", "se_stop", "v", "i")
  ME_STOP = Win32API.new(DLL + "FmodMS.dll", "me_stop", "v", "i")
  BGM_DOWN = Win32API.new(DLL + "FmodMS.dll", "bgm_volume_down", "li", "i")
  BGS_DOWN = Win32API.new(DLL + "FmodMS.dll", "bgs_volume_down", "li", "i")
  ME_DOWN = Win32API.new(DLL + "FmodMS.dll", "me_volume_down", "li", "i")
  BGM_IS_PLAYING = Win32API.new(DLL + "FmodMS.dll", "bgm_is_playing", "v", "i")
  BGS_IS_PLAYING = Win32API.new(DLL + "FmodMS.dll", "bgs_is_playing", "v", "i")
  SE_IS_PLAYING = Win32API.new(DLL + "FmodMS.dll", "se_is_playing", "v", "i")
  ME_IS_PLAYING = Win32API.new(DLL + "FmodMS.dll", "me_is_playing", "v", "i")
  WINDOWS_VER = Win32API.new("kernel32", "GetVersion", "v", "l")
  
  #--------------------------------------------------------------------------
  # ● 模塊方法
  #--------------------------------------------------------------------------
  module_function

  #--------------------------------------------------------------------------
  # ● 獲取Windows版本
  #--------------------------------------------------------------------------  
  def windows_version
    lngRetval = WINDOWS_VER.call
    lngMinor = (lngRetval & 0xff00) / 0x100
    lngMajor = (lngRetval & 0xff)
    if lngRetval & 0x800000000 == 0
      case [lngMajor, lngMinor]
      when [6, 1]
        return "Windows 7"
      when [6, 0]
        return "Windows Vista"
      when [5, 1]
        return "Windows XP"
      when [5, 0]
        return "Windows 2000"
      end
    elsif lngMajor == 4
      return "Windows ME"
    end
  end
  
  #--------------------------------------------------------------------------
  # ● 初始化引擎
  #--------------------------------------------------------------------------  
  def initialize_system
    INITIALIZE_SYSTEM.call(SOUND_TRACK)
  end
  
  #--------------------------------------------------------------------------
  # ● 播放BGM
  #--------------------------------------------------------------------------  
  def bgm_play(file, volume, pitch)
    BGM_PLAY.call(EasyConv.u2s(file), volume, pitch)
  end
  
  #--------------------------------------------------------------------------
  # ● 播放BGS
  #--------------------------------------------------------------------------
  def bgs_play(file, volume, pitch)
    BGS_PLAY.call(EasyConv.u2s(file), volume, pitch)
  end
  
  #--------------------------------------------------------------------------
  # ● 播放SE
  #--------------------------------------------------------------------------
  def se_play(file, volume, pitch)
    SE_PLAY.call(EasyConv.u2s(file), volume, pitch)
  end
  
  #--------------------------------------------------------------------------
  # ● 播放ME
  #--------------------------------------------------------------------------
  def me_play(file, volume, pitch)
    ME_PLAY.call(EasyConv.u2s(file), volume, pitch)
  end
  
  #--------------------------------------------------------------------------
  # ● 淡出BGM
  #--------------------------------------------------------------------------  
  def bgm_fade(fade_time)
    @fade_time = fade_time
    thread = Thread.new do
      BGM_DOWN.call(@fade_time, FORCE_CHANGE)
      while @fade_time > 0
        sleep(1)
        @fade_time -= 1000
        BGM_DOWN.call(0, NO_FORCE_CHANGE)
      end
      BGM_STOP.call
    end
  end
  
  #--------------------------------------------------------------------------
  # ● 淡出BGS
  #--------------------------------------------------------------------------  
  def bgs_fade(fade_time)
    @fade_time = fade_time
    thread = Thread.new do
      BGS_DOWN.call(@fade_time, FORCE_CHANGE)
      while @fade_time > 0
        sleep(1)
        @fade_time -= 1000
        BGS_DOWN.call(0, NO_FORCE_CHANGE)
      end
      BGS_STOP.call
    end
  end
  
  #--------------------------------------------------------------------------
  # ● 淡出ME
  #--------------------------------------------------------------------------  
  def me_fade(fade_time)
    @fade_time = fade_time
    thread = Thread.new do
      ME_DOWN.call(@fade_time, FORCE_CHANGE)
      while @fade_time > 0
        sleep(1)
        @fade_time -= 1000
        ME_DOWN.call(0, NO_FORCE_CHANGE)
      end
      ME_STOP.call
    end
  end
  
  #--------------------------------------------------------------------------
  # ● 停止BGM
  #--------------------------------------------------------------------------  
  def bgm_stop
    BGM_STOP.call
  end
  
  #--------------------------------------------------------------------------
  # ● 停止BGS
  #--------------------------------------------------------------------------  
  def bgs_stop
    BGS_STOP.call
  end
  
  #--------------------------------------------------------------------------
  # ● 停止SE
  #--------------------------------------------------------------------------  
  def se_stop
    SE_STOP.call
  end
  
  #--------------------------------------------------------------------------
  # ● 停止ME
  #--------------------------------------------------------------------------  
  def me_stop
    ME_STOP.call
  end
  
  #--------------------------------------------------------------------------
  # ● 判斷BGM播放情況
  #--------------------------------------------------------------------------  
  def bgm_is_playing
    BGM_IS_PLAYING.call
  end
  
  #--------------------------------------------------------------------------
  # ● 判斷BGS播放情況
  #--------------------------------------------------------------------------  
  def bgs_is_playing
    BGS_IS_PLAYING.call
  end
  
  #--------------------------------------------------------------------------
  # ● 判斷SE播放情況
  #--------------------------------------------------------------------------  
  def se_is_playing
    SE_IS_PLAYING.call
  end
  
  #--------------------------------------------------------------------------
  # ● 判斷ME播放情況
  #--------------------------------------------------------------------------  
  def me_is_playing
    ME_IS_PLAYING.call
  end
end

#--------------------------------------------------------------------------
# ● 初始化聲音引擎
#--------------------------------------------------------------------------
if FmodSoundSystem.windows_version == "Windows 7"\
  || FmodSoundSystem.windows_version == "Windows Vista"
  $init_result = FmodSoundSystem.initialize_system
else
  $init_result = 0
end

#--------------------------------------------------------------------------
# ● 判斷是否覆蓋原有的Audio
#--------------------------------------------------------------------------
