    end
  #--------------------------------------------------------------------------
  # ● 播放ME
  #--------------------------------------------------------------------------  
    def me_play(file, volume, pitch)
      FmodSoundSystem.me_play(file, volume, pitch)
    end
    
  #--------------------------------------------------------------------------
  # ● 停止BGM
  #--------------------------------------------------------------------------  
    def bgm_stop
      FmodSoundSystem.bgm_stop
    end
    
  #--------------------------------------------------------------------------
  # ● 停止BGS
  #--------------------------------------------------------------------------  
    def bgs_stop
      FmodSoundSystem.bgs_stop
    end
    
  #--------------------------------------------------------------------------
  # ● 停止SE
  #--------------------------------------------------------------------------  
    def se_stop
      FmodSoundSystem.se_stop
    end
    
  #--------------------------------------------------------------------------
  # ● 停止ME
  #--------------------------------------------------------------------------  
    def me_stop
      FmodSoundSystem.me_stop
    end
    
  #--------------------------------------------------------------------------
  # ● 淡出BGM
  #--------------------------------------------------------------------------  
    def bgm_fade(fade_time)
      FmodSoundSystem.bgm_fade(fade_time)
    end
    
  #--------------------------------------------------------------------------
  # ● 淡出BGS
  #--------------------------------------------------------------------------      
    def bgs_fade(fade_time)
      FmodSoundSystem.bgs_fade(fade_time)
    end
    
  #--------------------------------------------------------------------------
  # ● 淡出ME
  #--------------------------------------------------------------------------  
    def me_frad(fade_time)
      FmodSoundSystem.me_fade(fade_time)
    end
  end
end